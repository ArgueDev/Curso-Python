# Bucle de 0 a 4
for i in range(5):
    print(i)

print('-------')
# Bucle de 2 a 8 con salto de 2 (Incremento)
for i in range(2, 10, 2):
    print(i)

print('-------')
# Bucle de 10 a 0 con -1 (Decremento)
for i in range(10, 0, -1):
    print(i)

print('-------')
for i in range(10, -1, -1):
    print(i)

print('-------')
names = ['Andres', 'Pepe', 'Jhon', 'Juan']
for name in names:
    print(name)

print('-------')
# Secuencia de caracteres
email = 'correo@correo.com'
for char in email:
    print(char)