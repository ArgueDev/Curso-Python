# Operador de pertenencia

names = ['Andres', 'Maria', 'Josefa', 'Pepe']

result = 'andres' in names
print(f'Resultado = {result}')

result = 'Carlos' not in names
print(f'Carlos = {result}')

text = 'te' in 'Hola como estas?'
print(f'te = {text}')

text = 'H' in 'Hola como estas?'
print(f'H = {text}')