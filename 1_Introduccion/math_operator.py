# Operadores Matematicos

a = 10
b = 3.5

add = a + b
subtract = a - b
division = a / b
product = a * b
integer_division = a // b
module = a % b
pow = a ** 2

print(f'Suma: {add}')
print(f'Resta: {subtract}')
print(f'Division: {division}')
print(f'Multiplicacion: {product}')
print(f'Division Entera: {integer_division}')
print(f'Modulo de la division: {module}')
print(f'Potencia de 2: {pow}')